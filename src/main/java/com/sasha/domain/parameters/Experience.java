package com.sasha.domain.parameters;

public class Experience {

    private int currentExperience = 0;

    private int maxExperienceLevel = 0;


    public int getCurrentExperience() {
        return currentExperience;
    }

    public void setCurrentExperience(int currentExperience) {
        this.currentExperience = currentExperience;
    }

    public int getMaxExperienceLevel() {
        return maxExperienceLevel;
    }

    public void setMaxExperienceLevel(int maxExperienceLevel) {
        this.maxExperienceLevel = maxExperienceLevel;
    }
}
